import SwiftUI

/// 只读查看内核正在使用的配置，即配置文件依次合并配置覆写、全局覆写和应用设置后的结果
struct RuntimeConfigView: View {
    static let windowID = "runtime-config"

    @Environment(CoreManager.self) private var core

    var body: some View {
        Group {
            if let runtimeConfig = core.runtimeConfig {
                YAMLEditor(text: .constant(runtimeConfig), hint: "Generated by merging the profile, overrides, and app settings. Refreshes automatically when the core reloads.")
            } else {
                ContentUnavailableView("Core Not Running", systemImage: "doc.text", description: Text("The config passed to the core can be viewed once the core is running."))
                    .frame(minWidth: 520, minHeight: 360)
            }
        }
        .navigationTitle("Runtime Config")
    }
}
